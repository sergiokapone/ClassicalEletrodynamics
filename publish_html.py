#!/usr/bin/env python3
"""Moves the HTML book out of the TeX project into a separate folder (default: docs/) for GitHub Pages.

MOVED (only the site needs them; after the move the project root does not contain them):
  - generated by lwarp: pages (*.html with the lwarp tag; the intermediate *_html.html stays), lwarp*.css,
    sitemap.xml, lateximages/, <main>-images/, SVG made from a PDF picture (Pictures/x.pdf -> x.svg)
  - site files written by hand: SITE_OWN below (index.html, google*.html, assets/, serve.py). Moved once; from then on they
    live only in the output folder and are never wiped.
  - book.js and conspect.css (ASSET_FILES) end up in <out>/assets/ (also when they still lie in the project root or in the
    old place <out>/). postprocess_html.py (run before this) already points the pages there; links it missed are
    rewritten and book.js is added to a page that lacks it.
COPIED (the TeX project needs them too):
  - everything else the pages reference: pictures of the chapters, the PDF (linked from index.html), ... and --extra files
The same relative paths are kept, so the links work unchanged. On every run the output folder is emptied except
SITE_OWN, CNAME and dot-files, and .nojekyll is created.
After the move, folders of the project that are empty (<main>-images/, lateximages/, Pictures/ ...) are removed, and the
generated image folders are removed completely (leftover temporary files of lwarpmk).

Usage: python publish_html.py [--out docs] [--extra file ...] [--keep-leftovers]"""
import argparse, fnmatch, glob, os, posixpath, re, shutil, sys
from urllib.parse import unquote

SITE_OWN = ['index.html', 'google*.html', 'assets', 'serve.py']   # site-only files written by hand; edit here
ASSET_FILES = ['book.js', 'conspect.css']                # site-only files that live in <out>/assets/ (the pages link to them there)
ASSET_DIR = 'assets'

ap = argparse.ArgumentParser()
ap.add_argument('--out', default='docs')
ap.add_argument('--extra', nargs='*', default=[])
ap.add_argument('--keep-leftovers', action='store_true', help='do not delete what remains in lateximages/ and <main>-images/')
args = ap.parse_args()

ROOT = os.getcwd()
OUT = os.path.abspath(args.out)
if OUT == ROOT or ROOT.startswith(OUT + os.sep):
    sys.exit('ERROR: output folder must be a subfolder of the project, not %s' % OUT)

ATTR = re.compile(r'''\b(?:src|href|poster|data|data-src|data-href)\s*=\s*(["'])(.*?)\1''', re.I | re.S)
SRCSET = re.compile(r'''\bsrcset\s*=\s*(["'])(.*?)\1''', re.I | re.S)
CSSURL = re.compile(r'''url\(\s*(["']?)(.*?)\1\s*\)''', re.I)
CSSIMPORT = re.compile(r'''@import\s+(["'])(.*?)\1''')
EXTERNAL = re.compile(r'^(?:[a-zA-Z][a-zA-Z0-9+.\-]*:|//|#)')


def is_lwarp(path):
    try:
        with open(path, 'rb') as f:
            return b'lwarp' in f.read(4096).lower()
    except OSError:
        return False


def is_site_own(name):
    return any(fnmatch.fnmatch(name, p) for p in SITE_OWN)


def is_generated(rel, src):
    first, base = rel.split('/')[0], posixpath.basename(rel)
    if '/' in rel and (first == 'lateximages' or first.endswith('-images')): return True
    if '/' not in rel and (fnmatch.fnmatch(base, 'lwarp*.css') or base == 'sitemap.xml'): return True
    if base.endswith('.svg') and os.path.isfile(src[:-4] + '.pdf'): return True      # PDF picture converted by 'lwarpmk pdftosvg'
    return '/' not in rel and base.endswith('.html') and not base.endswith('_html.html') and is_lwarp(src)


_ls = {}
def exact_case(path, base):
    cur = base
    for part in os.path.relpath(path, base).split(os.sep):
        if cur not in _ls: _ls[cur] = set(os.listdir(cur))
        if part not in _ls[cur]: return False
        cur = os.path.join(cur, part)
    return True


def refs_of(path):
    ext = os.path.splitext(path)[1].lower()
    if ext not in ('.html', '.htm', '.css'): return []
    text = open(path, 'rb').read().decode('utf-8', errors='ignore')
    found = []
    if ext == '.css':
        found += [m.group(2) for m in CSSURL.finditer(text)] + [m.group(2) for m in CSSIMPORT.finditer(text)]
    else:
        found += [m.group(2) for m in ATTR.finditer(text)]
        for m in SRCSET.finditer(text):
            found += [p.strip().split()[0] for p in m.group(2).split(',') if p.strip()]
        found += [m.group(2) for m in CSSURL.finditer(text)]
    return found


# --- 0. book.js / conspect.css -> <out>/assets/ ---------------------------------------------------
# candidates: the project root (a fresh copy you edited there) and the old place <out>/ ; the newest one wins
os.makedirs(os.path.join(OUT, ASSET_DIR), exist_ok=True)
moved_assets = []
for name in ASSET_FILES:
    dst = os.path.join(OUT, ASSET_DIR, name)
    cands = [p for p in (os.path.join(ROOT, name), os.path.join(OUT, name), dst) if os.path.isfile(p)]
    if not cands: continue
    best = max(cands, key=os.path.getmtime)
    if best != dst:
        shutil.copy2(best, dst); moved_assets.append(name)
    for p in cands:
        if p != dst: os.remove(p)                                  # the old copies are gone: one file, one place

# --- 1. empty the output folder (site files stay) -------------------------------------------------
if not any(os.path.isfile(p) and is_lwarp(p) and not p.endswith('_html.html') for p in glob.glob(os.path.join(ROOT, '*.html'))):
    sys.exit('ERROR: no lwarp pages (*.html) found in %s - run the HTML build first' % ROOT)
os.makedirs(OUT, exist_ok=True)
# --extra files that are not in the project root but already in the output folder (e.g. the PDF of the book) stay
keep_extra = {e.replace('\\', '/') for e in args.extra if not os.path.isfile(os.path.join(ROOT, e)) and os.path.isfile(os.path.join(OUT, e))}
for name in os.listdir(OUT):
    if name == 'CNAME' or name.startswith('.') or is_site_own(name) or name in keep_extra: continue
    p = os.path.join(OUT, name)
    shutil.rmtree(p, ignore_errors=True) if os.path.isdir(p) else os.remove(p)
open(os.path.join(OUT, '.nojekyll'), 'w').close()

# --- 2. site files: root -> output folder (only if they are still in the root) --------------------
moved_site = []
for name in sorted(os.listdir(ROOT)):
    if not is_site_own(name): continue
    src, dst = os.path.join(ROOT, name), os.path.join(OUT, name)
    if os.path.isdir(dst) and os.path.isdir(src): shutil.rmtree(dst)
    elif os.path.exists(dst): os.remove(dst)
    shutil.move(src, dst); moved_site.append(name)

# --- 3. collect: seeds, then follow the references ------------------------------------------------
sources = {}                  # site-relative path -> real file
queue = []                    # site-relative paths still to scan
missing, badcase, outside = {}, [], []

def add(rel, src):
    if rel not in sources: sources[rel] = src; queue.append(rel)

def find(rel):
    for base in (ROOT, OUT):
        p = os.path.join(base, *rel.split('/'))
        if os.path.isfile(p): return p, base
    return None, None

for p in glob.glob(os.path.join(ROOT, '*.html')) + glob.glob(os.path.join(ROOT, 'sitemap.xml')):
    if p.endswith('_html.html'): continue
    if p.endswith('.html') and not is_lwarp(p): continue
    add(os.path.basename(p), p)
for p in glob.glob(os.path.join(OUT, '**', '*'), recursive=True):          # site files that already live in OUT
    rel = os.path.relpath(p, OUT).replace(os.sep, '/')
    if os.path.isfile(p) and not rel.startswith('.') and is_site_own(rel.split('/')[0]): add(rel, p)
for e in args.extra:
    p = os.path.join(ROOT, e)
    if os.path.isfile(p): add(e.replace('\\', '/'), p)
    elif os.path.isfile(os.path.join(OUT, e)): add(e.replace('\\', '/'), os.path.join(OUT, e))
    else: missing.setdefault(e, '--extra')

i = 0
while i < len(queue):
    rel_src = queue[i]; i += 1
    for ref in refs_of(sources[rel_src]):
        ref = ref.strip()
        if not ref or EXTERNAL.match(ref): continue
        ref = unquote(ref.split('#')[0].split('?')[0]).replace('\\', '/')
        if not ref or ref.startswith('pagefind/'): continue          # the search index: built after publishing
        rel = posixpath.normpath(ref[1:] if ref.startswith('/') else posixpath.join(posixpath.dirname(rel_src), ref))
        if rel in ASSET_FILES: rel = ASSET_DIR + '/' + rel          # the pages say conspect.css; it lives in assets/
        if rel.startswith('..'):
            outside.append((rel_src, ref)); continue
        p, base = find(rel)
        if p is None:
            if not os.path.isdir(os.path.join(ROOT, *rel.split('/'))) and not os.path.isdir(os.path.join(OUT, *rel.split('/'))):
                missing.setdefault(rel, rel_src)
            continue
        if not exact_case(p, base): badcase.append((rel, rel_src))
        add(rel, p)

# --- 4. move generated files, copy the rest ------------------------------------------------------
n_move = n_copy = n_have = 0
size = 0
moved_from = []
for rel, src in sorted(sources.items()):
    if os.path.commonpath([src, OUT]) == OUT:
        n_have += 1; continue                                  # already in the output folder
    dst = os.path.join(OUT, *rel.split('/'))
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if is_generated(rel, src): shutil.move(src, dst); n_move += 1; moved_from.append(src)
    else: shutil.copy2(src, dst); n_copy += 1
    size += os.path.getsize(dst)

# --- 5. the pages: links to assets/, book.js on every page ---------------------------------------
LINK_CSS = re.compile(r'''(\bhref\s*=\s*["'])(?:\./)?conspect\.css(["'])''', re.I)
LINK_JS = re.compile(r'''(\bsrc\s*=\s*["'])(?:\./)?book\.js(["'])''', re.I)
# (search marks, links to index.html and the PDF, contents titles: postprocess_html.py, before this script)

n_pages = n_script = 0
for name in sorted(os.listdir(OUT)):
    if not name.endswith('.html') or is_site_own(name): continue
    path = os.path.join(OUT, name)
    text = open(path, 'rb').read().decode('utf-8')
    new = LINK_CSS.sub(r'\1%s/conspect.css\2' % ASSET_DIR, text)
    new = LINK_JS.sub(r'\1%s/book.js\2' % ASSET_DIR, new)
    if 'book.js' not in new and '</head>' in new:             # in <head> without defer: the theme is set before the first paint
        new = new.replace('</head>', '<script src="%s/book.js"></script>\n</head>' % ASSET_DIR, 1); n_script += 1
    if new != text:
        open(path, 'wb').write(new.encode('utf-8')); n_pages += 1
for rel in ASSET_FILES:
    if not os.path.isfile(os.path.join(OUT, ASSET_DIR, rel)):
        print('  WARNING: %s/%s not found: the pages link to it' % (ASSET_DIR, rel))

# --- 6. the project root: no empty folders left behind ---------------------------------------------
removed_dirs, leftovers = [], 0
if not args.keep_leftovers:                                      # generated image folders: all that is needed is already moved
    for d in sorted(os.listdir(ROOT)):
        p = os.path.join(ROOT, d)
        if os.path.isdir(p) and (d == 'lateximages' or d.endswith('-images')):
            leftovers += sum(len(fs) for _, _, fs in os.walk(p))
            shutil.rmtree(p, ignore_errors=True)
            if not os.path.isdir(p): removed_dirs.append(d)
for src in moved_from:                                           # folders the moved files came from (and their empty parents)
    d = os.path.dirname(src)
    while d != ROOT and d.startswith(ROOT + os.sep):
        try: os.rmdir(d)
        except OSError: break                                    # not empty (or in use): stop
        removed_dirs.append(os.path.relpath(d, ROOT).replace(os.sep, '/'))
        d = os.path.dirname(d)

print('  output folder %s: %d files moved out of the project, %d copied, %d site files already there (%.1f MB new)'
      % (os.path.relpath(OUT, ROOT), n_move, n_copy, n_have, size / 1048576))
if moved_site: print('  site files moved from the project root (once): %s' % ', '.join(moved_site))
if moved_assets: print('  moved to %s/%s/: %s' % (os.path.relpath(OUT, ROOT), ASSET_DIR, ', '.join(moved_assets)))
print('  pages: %d rewritten (links to %s/), book.js added to %d' % (n_pages, ASSET_DIR, n_script))
if removed_dirs: print('  removed from the project root: %s' % ', '.join(d + '/' for d in sorted(set(removed_dirs))))
if leftovers: print('  (deleted %d leftover temporary files of lwarpmk in the image folders)' % leftovers)
for f, where in sorted(missing.items()):
    print('  WARNING: referenced file not found: %s   (from %s)' % (f, where))
for f, where in badcase:
    print('  WARNING: letter case differs from the real file name (works on Windows, breaks on GitHub): %s   (from %s)' % (f, where))
for where, ref in outside:
    print('  WARNING: reference outside the site is not copied: %s   (from %s)' % (ref, where))
